def plot_parameter_sweep(
    df: pd.DataFrame,
    output_dir: Path,
    figsize: tuple = (14, 6),
    dpi: int = 150,
):
    """Line charts showing metric means as a function of parameter value.

    Expects columns ``param_name`` and ``param_value`` (added by the pipeline).
    Produces one chart per transformation type (twirl / spherize).
    """
    if "param_name" not in df.columns or "param_value" not in df.columns:
        print("  Sweep visualisation skipped (no param_name/param_value columns)")
        return

    change_cols = [c for c in CHANGE_METRICS if c in df.columns]
    quality_cols = [c for c in QUALITY_METRICS if c in df.columns]

    for param_name, grp in df.groupby("param_name"):
        param_vals = sorted(grp["param_value"].unique())
        if len(param_vals) < 2:
            continue

        # --- Change metrics sweep ---
        if change_cols:
            fig, ax = plt.subplots(figsize=figsize)
            for col in change_cols:
                means = [grp[grp["param_value"] == v][col].mean() for v in param_vals]
                stds = [grp[grp["param_value"] == v][col].std() for v in param_vals]
                label = CHANGE_LABELS.get(col, col)
                ax.errorbar(param_vals, means, yerr=stds, marker="o", capsize=3, label=label)

            ax.set_xlabel(param_name.replace("_", " ").title())
            ax.set_ylabel("Metric value")
            n_per = len(grp) // len(param_vals)
            ax.set_title(f"Change Metrics vs {param_name.replace('_', ' ').title()} [n={n_per}/param]")
            ax.legend(fontsize=7, ncol=2)
            ax.set_xticks(param_vals)
            plt.tight_layout()
            path = output_dir / f"sweep_change_{param_name}.png"
            plt.savefig(path, dpi=dpi, bbox_inches="tight")
            plt.close(fig)
            print(f"  Sweep chart → {path}")

        # --- Quality metrics sweep ---
        if quality_cols:
            fig, ax = plt.subplots(figsize=figsize)
            for col in quality_cols:
                means = [grp[grp["param_value"] == v][col].mean() for v in param_vals]
                stds = [grp[grp["param_value"] == v][col].std() for v in param_vals]
                label = QUALITY_LABELS.get(col, col)
                ax.errorbar(param_vals, means, yerr=stds, marker="o", capsize=3, label=label)

            ax.set_xlabel(param_name.replace("_", " ").title())
            ax.set_ylabel("Metric value")
            n_per = len(grp) // len(param_vals)
            ax.set_title(f"Quality Metrics vs {param_name.replace('_', ' ').title()} [n={n_per}/param]")
            ax.legend(fontsize=7)
            ax.set_xticks(param_vals)
            plt.tight_layout()
            path = output_dir / f"sweep_quality_{param_name}.png"
            plt.savefig(path, dpi=dpi, bbox_inches="tight")
            plt.close(fig)
            print(f"  Sweep chart → {path}")


