def _load_image_triple(
    original_dir: Path,
    generated_dir: Path,
    row: pd.Series,
) -> tuple[np.ndarray, np.ndarray, np.ndarray] | None:
    """Load original, manipulated, and mask images for one metadata row."""
    filename = row["filename"]
    has_t = "transformation" in row.index and pd.notna(row.get("transformation"))

    if has_t:
        t = str(row["transformation"])
        manip_path = generated_dir / t / filename
        mask_path = generated_dir / t / "masks" / filename
    else:
        manip_path = generated_dir / filename
        mask_path = generated_dir / "masks" / filename

    orig_path = original_dir / filename

    for p in (orig_path, manip_path, mask_path):
        if not p.exists():
            return None

    orig = cv.imread(str(orig_path), cv.IMREAD_GRAYSCALE)
    manip = cv.imread(str(manip_path), cv.IMREAD_GRAYSCALE)
    mask = cv.imread(str(mask_path), cv.IMREAD_GRAYSCALE)
    if orig is None or manip is None or mask is None:
        return None

    _, mask = cv.threshold(mask, 127, 255, cv.THRESH_BINARY)
    return orig, manip, mask


def plot_spatial_heatmaps(
    rows: pd.DataFrame,
    original_dir: Path,
    generated_dir: Path,
    output_path: Path,
    figsize,
    dpi,
):
    """Unified spatial overlay for one image: one row per distortion method.

    Columns: Original | Generated | |Diff| | Sobel diff | Laplacian diff
    The crop region is derived from the first row's mask and shared across rows.
    """
    # Determine crop bounds from the first row's mask
    first_result = _load_image_triple(original_dir, generated_dir, rows.iloc[0])
    if first_result is None:
        return False
    _, _, mask_ref = first_result
    ys, xs = np.where(mask_ref > 0)
    pad = 30
    y1 = max(ys.min() - pad, 0)
    y2 = min(ys.max() + pad, mask_ref.shape[0])
    x1 = max(xs.min() - pad, 0)
    x2 = min(xs.max() + pad, mask_ref.shape[1])

    n_rows = len(rows)
    col_titles = ["Original", "Generated", "|Pixel Diff|", "Sobel diff", "Laplacian diff"]
    fig, axes = plt.subplots(n_rows, 5, figsize=(figsize[0], figsize[1] * n_rows))
    if n_rows == 1:
        axes = axes[np.newaxis, :]

    for ax, title in zip(axes[0], col_titles):
        ax.set_title(title, fontsize=10)

    for row_idx, (_, row) in enumerate(rows.iterrows()):
        result = _load_image_triple(original_dir, generated_dir, row)
        if result is None:
            for ax in axes[row_idx]:
                ax.tick_params(left=False, bottom=False, labelleft=False, labelbottom=False)
                for spine in ax.spines.values():
                    spine.set_visible(False)
            continue

        orig, manip, _ = result
        diff = np.abs(manip.astype(np.float64) - orig.astype(np.float64))
        sobel_orig = np.sqrt(cv.Sobel(orig, cv.CV_64F, 1, 0, ksize=3) ** 2 + cv.Sobel(orig, cv.CV_64F, 0, 1, ksize=3) ** 2)
        sobel_manip = np.sqrt(cv.Sobel(manip, cv.CV_64F, 1, 0, ksize=3) ** 2 + cv.Sobel(manip, cv.CV_64F, 0, 1, ksize=3) ** 2)
        lap_orig = cv.Laplacian(orig, cv.CV_64F, ksize=3)
        lap_manip = cv.Laplacian(manip, cv.CV_64F, ksize=3)

        panels = [
            orig[y1:y2, x1:x2],
            manip[y1:y2, x1:x2],
            diff[y1:y2, x1:x2],
            np.abs(sobel_manip - sobel_orig)[y1:y2, x1:x2],
            np.abs(lap_manip - lap_orig)[y1:y2, x1:x2],
        ]
        cmaps = ["gray", "gray", "inferno", "inferno", "inferno"]

        t_label = row.get("transformation", "")

        for col_idx, (ax, img, cmap) in enumerate(zip(axes[row_idx], panels, cmaps)):
            ax.imshow(img, cmap=cmap)
            ax.tick_params(left=False, bottom=False, labelleft=False, labelbottom=False)
            for spine in ax.spines.values():
                spine.set_visible(False)
            if col_idx == 0:
                ax.set_ylabel(t_label, fontsize=10, rotation=0, labelpad=50, va="center")

    fname = Path(rows.iloc[0]["filename"]).stem
    fig.suptitle(fname, fontsize=11)
    plt.tight_layout()
    plt.savefig(output_path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)
    return True


