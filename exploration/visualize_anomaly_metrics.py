def plot_radar(df: pd.DataFrame, output_path: Path, figsize, dpi):
    """Radar chart of normalized metric means per transformation."""
    cols = [c for c in CHANGE_METRICS if c in df.columns]
    labels = [CHANGE_LABELS.get(c, c) for c in cols]
    n = len(cols)
    angles = np.linspace(0, 2 * np.pi, n, endpoint=False).tolist()
    angles += angles[:1]

    fig, ax = plt.subplots(figsize=figsize, subplot_kw={"polar": True})

    # Normalize by global max per metric
    global_max = df[cols].max()

    if _has_groups(df):
        groups = sorted(df["transformation"].unique())
        for group in groups:
            sub = df[df["transformation"] == group]
            values = [(sub[c].mean() / (global_max[c] + 1e-12)) for c in cols]
            values += values[:1]
            ax.plot(angles, values, "o-", linewidth=2, label=group)
            ax.fill(angles, values, alpha=0.15)
    else:
        values = [(df[c].mean() / (global_max[c] + 1e-12)) for c in cols]
        values += values[:1]
        ax.plot(angles, values, "o-", linewidth=2, label="all")
        ax.fill(angles, values, alpha=0.15)

    ax.set_thetagrids(np.degrees(angles[:-1]), labels, size=8)
    ax.set_ylim(0, 1.1)
    ax.set_title(f"Masked Region Metric Profiles (normalized by distortion method) [n={len(df)}]", y=1.08)
    ax.legend(loc="upper right", bbox_to_anchor=(1.25, 1.1))
    plt.tight_layout()
    plt.savefig(output_path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)


