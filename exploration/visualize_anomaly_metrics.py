    generated_dir = Path(config.get("generated_dir", ""))
    dpi = config.get("dpi", 150)
    num_spatial = config.get("num_spatial_samples", 3)

    # Update metric lists from config if provided
    if "visualize_change_metrics" in config and config["visualize_change_metrics"] is not None:
        CHANGE_METRICS = config["visualize_change_metrics"]
    if "visualize_quality_metrics" in config and config["visualize_quality_metrics"] is not None:
        QUALITY_METRICS = config["visualize_quality_metrics"]

    output_dir.mkdir(parents=True, exist_ok=True)

    metrics_csv = metrics_dir / "metrics.csv"
    if not metrics_csv.exists():
        print(f"metrics.csv not found in {metrics_dir}")
        return

    df = pd.read_csv(metrics_csv)
    print(f"Loaded {len(df)} rows from {metrics_csv}")

    # 1. Grouped bar chart
    path = output_dir / "bar_chart.png"
    plot_grouped_bar(df, path, tuple(config.get("figsize_bar", [14, 6])), dpi)
    print(f"  [1/5] Bar chart → {path}")

    # 2. Box / violin plots
    path_box = output_dir / "box_plots.png"
    path_violin = output_dir / "violin_plots.png"
    plot_box_violin(df, path_box, path_violin, tuple(config.get("figsize_box", [14, 6])), dpi)
    print(f"  [2/5] Box plots → {path_box}")
    print(f"  [2/5] Violin plots → {path_violin}")

    # 3. Radar chart
    path = output_dir / "radar_chart.png"
    plot_radar(df, path, tuple(config.get("figsize_radar", [8, 8])), dpi)
    print(f"  [3/5] Radar chart → {path}")

    # 4. Correlation heatmap
    path = output_dir / "correlation_heatmap.png"
    plot_correlation(df, path, tuple(config.get("figsize_heatmap", [10, 8])), dpi)
    print(f"  [4/5] Correlation heatmap → {path}")

    # 5. Spatial heatmap overlays
    if original_dir.exists() and generated_dir.exists():
        spatial_dir = output_dir / "spatial_heatmaps"
        spatial_dir.mkdir(exist_ok=True)

        # Sample images: pick the same filenames across all transformations
        if _has_groups(df):
            top_files = (
                df.groupby("filename")["pixel_mae"]
                .mean()
                .nlargest(num_spatial)
                .index
            )
            samples = df[df["filename"].isin(top_files)]
        else:
            samples = df.nlargest(num_spatial, "pixel_mae")

        count = 0
        for fname, file_rows in samples.groupby("filename"):
            stem = Path(fname).stem
            out_path = spatial_dir / f"{stem}.png"
            ok = plot_spatial_heatmaps(
                file_rows, original_dir, generated_dir, out_path,
                tuple(config.get("figsize_spatial", [16, 4])), dpi,
            )
            if ok:
                count += 1
                print(f"  [5/5] Spatial overlay → {out_path.name}")

        if count == 0:
            print("  [5/5] No spatial overlays generated (missing source images)")
    else:
        print("  [5/5] Skipped spatial overlays (original_dir / generated_dir not set)")

    # 6. Quality metrics
    path_quality_bar = output_dir / "quality_bar_chart.png"
    plot_quality_bar(df, path_quality_bar, tuple(config.get("figsize_bar", [14, 6])), dpi)
    print(f"  [6/8] Quality bar chart → {path_quality_bar}")

    path_quality_box = output_dir / "quality_box_plots.png"
    path_quality_violin = output_dir / "quality_violin_plots.png"
    plot_quality_box_violin(df, path_quality_box, path_quality_violin, tuple(config.get("figsize_box", [14, 6])), dpi)
    print(f"  [7/8] Quality box plots → {path_quality_box}")
    print(f"  [8/8] Quality violin plots → {path_quality_violin}")

    print(f"\nAll visualizations saved to: {output_dir}")


