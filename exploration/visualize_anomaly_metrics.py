def plot_correlation(df: pd.DataFrame, output_path: Path, figsize, dpi):
    """Pearson correlation heatmap of all numeric metrics."""
    cols = _get_metric_cols(df)
    corr = df[cols].corr()

    fig, ax = plt.subplots(figsize=figsize)
    im = ax.imshow(corr.values, cmap="RdBu_r", vmin=-1, vmax=1, aspect="auto")
    ax.set_xticks(range(len(cols)))
    ax.set_yticks(range(len(cols)))
    short = [CHANGE_LABELS.get(c, c.replace("_", "\n", 1)) for c in cols]
    ax.set_xticklabels(short, rotation=45, ha="right", fontsize=6)
    ax.set_yticklabels(short, fontsize=6)
    fig.colorbar(im, ax=ax, shrink=0.8, label="Pearson r")
    ax.set_title(f"Masked Region Metric Correlations [n={len(df)}]")
    plt.tight_layout()
    plt.savefig(output_path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)


