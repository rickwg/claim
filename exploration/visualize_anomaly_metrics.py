"""
Visualize anomaly distortion metrics.

Produces five types of plots from the metrics CSV generated by
anomaly_distortion_metrics.py:

  1. Grouped bar chart   – mean ± std per metric, grouped by transformation
  2. Box / violin plots  – full distribution per metric and transformation
  3. Radar / spider chart – normalized metric profiles per transformation
  4. Correlation heatmap  – pairwise Pearson correlation between metrics
  5. Spatial heatmap overlay – per-pixel |diff|, Sobel, Laplacian on mammograms

Usage:
    python exploration/visualize_anomaly_metrics.py --config config/visualize_anomaly_metrics.yaml
"""

import argparse
from pathlib import Path

import cv2 as cv
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import yaml


def load_config(config_path: str) -> dict:
    """Load configuration from YAML file."""
    with open(config_path, "r") as f:
        return yaml.safe_load(f)


# ---------------------------------------------------------------------------
# Metric grouping helpers
# ---------------------------------------------------------------------------

# Metrics that measure the *change* caused by the distortion (good for comparing transforms)
CHANGE_METRICS = [
    "pixel_mae",
    "pixel_rmse",
    "pixel_max_diff",
    "sobel_mae",
    "laplacian_mae",
    "border_intensity_step_manip",
    "border_pixel_mae_manip",
    "border_intensity_step_diff",
    "border_pixel_mae_diff",
]

# Integration quality metrics (higher is better for SSIM, lower for distance metrics)
QUALITY_METRICS = [
    "ssim",
    "histogram_dist",
    "local_contrast_diff",
]

# Short display labels for the change metrics
CHANGE_LABELS = {
    "pixel_mae": "Pixel MAE",
    "pixel_rmse": "Pixel RMSE",
    "pixel_max_diff": "Pixel Max diff",
    "sobel_mae": "Sobel MAE",
    "laplacian_mae": "Laplacian MAE",
    "border_intensity_step_manip": "Border int diff",
    "border_pixel_mae_manip": "Border pixel MAE",
    "border_intensity_step_diff": "Border int step Δ",
    "border_pixel_mae_diff": "Border pixel MAE Δ",
}

# Short display labels for quality metrics
QUALITY_LABELS = {
    "ssim": "SSIM",
    "histogram_dist": "Histogram distance",
    "local_contrast_diff": "Local contrast diff",
}


def _get_metric_cols(df: pd.DataFrame) -> list[str]:
    """Return all numeric metric column names."""
    skip = {"filename", "transformation"}
    return [c for c in df.columns if c not in skip and pd.api.types.is_numeric_dtype(df[c])]


def _has_groups(df: pd.DataFrame) -> bool:
    return "transformation" in df.columns and df["transformation"].nunique() > 1


# ---------------------------------------------------------------------------
# 1. Grouped bar chart
# ---------------------------------------------------------------------------


def plot_grouped_bar(df: pd.DataFrame, output_path: Path, figsize, dpi):
    """Mean ± std of change metrics, grouped by transformation."""
    cols = [c for c in CHANGE_METRICS if c in df.columns]
    labels = [CHANGE_LABELS.get(c, c) for c in cols]

    fig, ax = plt.subplots(figsize=figsize)

    if _has_groups(df):
        groups = sorted(df["transformation"].unique())
        n_groups = len(groups)
        x = np.arange(len(cols))
        width = 0.8 / n_groups

        for i, group in enumerate(groups):
            sub = df[df["transformation"] == group]
            means = [sub[c].mean() for c in cols]
            stds = [sub[c].std() for c in cols]
            # Asymmetric error bars: lower bound clipped at 0, upper extends normally
            lower_err = [max(0, m - s) for m, s in zip(means, stds)]
            upper_err = stds
            yerr = [np.array(lower_err), np.array(upper_err)]
            offset = (i - (n_groups - 1) / 2) * width
            ax.bar(x + offset, means, width, yerr=yerr, label=group, capsize=3)

        ax.legend()
    else:
        means = [df[c].mean() for c in cols]
        stds = [df[c].std() for c in cols]
        lower_err = [max(0, m - s) for m, s in zip(means, stds)]
        upper_err = stds
        yerr = [np.array(lower_err), np.array(upper_err)]
        ax.bar(range(len(cols)), means, yerr=yerr, capsize=3)

    ax.set_xticks(range(len(cols)))
    ax.set_xticklabels(labels)
    ax.set_ylabel("Value")
    ax.set_title(f"Masked Region Change (mean ± std by distortion method) [n={len(df)}]")
    plt.tight_layout()
    plt.savefig(output_path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)


# ---------------------------------------------------------------------------
# 2. Box / violin plots
# ---------------------------------------------------------------------------


def plot_box_violin(df: pd.DataFrame, output_path_box: Path, output_path_violin: Path, figsize, dpi):
    """Create separate box and violin plots for change metrics, split by transformation."""
    cols = [c for c in CHANGE_METRICS if c in df.columns]
    labels = [CHANGE_LABELS.get(c, c) for c in cols]

    # Normalize each metric to [0, 1] so they share a y-axis
    normed = df[cols].copy()
    for c in cols:
        cmin, cmax = normed[c].min(), normed[c].max()
        normed[c] = (normed[c] - cmin) / (cmax - cmin + 1e-12)

    if _has_groups(df):
        normed["transformation"] = df["transformation"]

    # Box plot
    fig_box, ax_box = plt.subplots(figsize=figsize)

    if _has_groups(df):
        groups = sorted(df["transformation"].unique())
        colors = plt.cm.tab10.colors
        legend_handles = []

        spacing = len(groups) + 1
        for gi, group in enumerate(groups):
            sub = normed[normed["transformation"] == group][cols].values
            positions = [spacing * i + gi for i in range(len(cols))]
            bp = ax_box.boxplot(
                sub,
                positions=positions,
                widths=0.6,
                patch_artist=True,
                showfliers=False,
            )
            for patch in bp["boxes"]:
                patch.set_facecolor(colors[gi % len(colors)])
                patch.set_alpha(0.7)
            legend_handles.append(plt.Rectangle((0, 0), 1, 1, fc=colors[gi % len(colors)], alpha=0.7))

        ax_box.set_xticks([spacing * i + (len(groups) - 1) / 2 for i in range(len(cols))])
        ax_box.set_xticklabels(labels)
        ax_box.legend(legend_handles, groups)
    else:
        ax_box.boxplot(normed[cols].values, showfliers=False)
        ax_box.set_xticks(range(1, len(cols) + 1))
        ax_box.set_xticklabels(labels)

    ax_box.set_ylabel("Normalized value")
    ax_box.set_title(f"Masked Region Change Distribution (box plots by distortion method) [n={len(df)}]")
    plt.tight_layout()
    plt.savefig(output_path_box, dpi=dpi, bbox_inches="tight")
    plt.close(fig_box)

    # Violin plot
    fig_violin, ax_violin = plt.subplots(figsize=figsize)

    if _has_groups(df):
        for gi, group in enumerate(groups):
            sub = normed[normed["transformation"] == group][cols].values
            positions = [spacing * i + gi for i in range(len(cols))]
            parts = ax_violin.violinplot(
                sub,
                positions=positions,
                widths=0.6,
                showmeans=True,
                showmedians=False,
            )
            for pc in parts["bodies"]:
                pc.set_facecolor(colors[gi % len(colors)])
                pc.set_alpha(0.7)

        ax_violin.set_xticks([spacing * i + (len(groups) - 1) / 2 for i in range(len(cols))])
        ax_violin.set_xticklabels(labels)
        ax_violin.legend(legend_handles, groups)
    else:
        ax_violin.violinplot(normed[cols].values, showmeans=True, showmedians=False)
        ax_violin.set_xticks(range(1, len(cols) + 1))
        ax_violin.set_xticklabels(labels)

    ax_violin.set_ylabel("Normalized value")
    ax_violin.set_title(f"Masked Region Change Distribution (violin plots by distortion method) [n={len(df)}]")
    plt.tight_layout()
    plt.savefig(output_path_violin, dpi=dpi, bbox_inches="tight")
    plt.close(fig_violin)


